package hashset;

import java.util.*;
public class Hashset_Ex1 
{
	public static void main(String []args)
	{
		HashSet<String> fruits=new HashSet<>();
		fruits.add("apple");
		fruits.add("orange");
		fruits.add("banana");
		fruits.add("mango");
		fruits.add("grapes");
		
		System.out.println(fruits);
	}
}
